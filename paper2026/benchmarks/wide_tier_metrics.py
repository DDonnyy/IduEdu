"""Every headline number of the wide tier, in one table each figure can be checked against.

Writes ``results/wide_tier/METRICS.md``. The point is that a reader of the figures
can find the number behind every bar without opening a notebook, and that a rerun
of the sweeps regenerates the text rather than leaving a stale copy in the paper.

    python benchmarks/wide_tier_metrics.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "figures"))

from figure_common import (  # noqa: E402
    CASE_ORDER,
    MODE_ORDER,
    NO_NETWORK,
    RESULTS,
    WAIT_MODE_ORDER,
    classify_bus,
    load,
)
from wide_cohort import excluded
from wide_cohort import measurable as cohort_cities  # noqa: E402

OUTPUT = RESULTS / "METRICS.md"


def section(title: str) -> str:
    return f"\n## {title}\n\n"


def table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(frame.columns) + " |\n"
    header += "|" + "|".join("---" for _ in frame.columns) + "|\n"
    rows = "".join("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |\n" for row in frame.to_numpy())
    return header + rows


def build() -> str:
    out = [
        "# Wide tier — every headline number\n",
        "Generated by `benchmarks/wide_tier_metrics.py`. Figures live in `figures/wide_*.png`.\n",
    ]

    # --- the sample -------------------------------------------------------
    # The funnel is the one place that must see everything: its whole point is to
    # count what fell out before the cohort was formed.
    selection = load("selection.csv", ["feed_id"], cohort=False)
    downloads = load("downloads.csv", ["feed_id"], cohort=False)
    profile = load("feed_profile.csv", ["feed_id"], cohort=False)
    cities = load("cities.csv", ["city_key"], cohort=False)
    feeds = load("city_feeds.csv", ["city_key"], cohort=False)
    osm = load("osm_graphs.csv", ["city_key", "kind"])
    gtfs = load("gtfs_graphs.csv", ["city_key"])
    access = load("accessibility.csv", ["city_key"])

    out.append(section("The sample, and what it cost to get it"))
    funnel = pd.DataFrame(
        [
            ("selected from catalogues", len(selection)),
            ("downloaded successfully", int((downloads["status"] == "ok").sum())),
            ("passed GTFS validation", int(profile["ok"].astype(str).str.lower().isin(["true", "1"]).sum())),
            (
                "resolved to a city with a boundary",
                int(cities["has_usable_boundary"].astype(str).str.lower().isin(["true", "1"]).sum()),
            ),
            ("merged into a city feed", int((feeds["status"] == "ok").sum())),
            ("in the study cohort: a feed and a boundary", len(cohort_cities())),
            ("OSM transit graph built", int(((osm["kind"] == "pt") & (osm["status"] == "ok")).sum())),
            ("pedestrian graph built", int(((osm["kind"] == "walk") & (osm["status"] == "ok")).sum())),
            ("GTFS reference graph built", int(gtfs["status"].isin(["ok", "cached"]).sum())),
            ("accessibility compared", int((access["status"] == "ok").sum())),
        ],
        columns=["stage", "count"],
    )
    out.append(table(funnel))

    # The cohort is where a reader can check that the tables below share one
    # denominator. Cities that fall out of it are named, not quietly missing.
    left_out = excluded()
    if not left_out.empty:
        out.append(
            f"\nMerged but outside the cohort ({len(left_out)}): "
            + "; ".join(f"{row.city_key} — {row.reason}" for row in left_out.itertuples())
            + ". A city needs a boundary to enter the study, because the boundary is "
            "what makes the two sides comparable: one OSM relation clips the feed and "
            "the OSM extract alike.\n"
        )

    walk = osm.loc[osm["kind"].eq("walk") & osm["status"].eq("ok")]
    transit = osm.loc[osm["kind"].eq("pt") & osm["status"].eq("ok")]
    out.append(
        f"\nGraph sizes: pedestrian {int(walk['n_nodes'].sum()):,} nodes / {int(walk['n_edges'].sum()):,} edges; "
        f"OSM transit {int(transit['n_nodes'].sum()):,} / {int(transit['n_edges'].sum()):,}; "
        f"GTFS reference {int(gtfs['n_nodes'].fillna(0).sum()):,} / {int(gtfs['n_edges'].fillna(0).sum()):,}.\n"
    )

    # --- data defects -----------------------------------------------------
    out.append(section("Defects in published feeds, repaired at merge time"))
    repairs = []
    for column, label in (
        ("colliding_rows_dropped", "one identifier used for different objects"),
        ("repeated_rows_dropped", "byte-identical duplicate rows"),
        ("unusable_frequencies_dropped", "frequency rows with an empty window"),
        ("trips_dropped_bad_times", "trips whose times run backwards or never close"),
        ("orphan_rows_dropped", "rows referencing identifiers no table defines"),
    ):
        if column not in feeds:
            continue
        values = feeds[column].fillna(0)
        repairs.append(
            {"defect": label, "rows or trips": int(values.sum()), "cities affected": int((values > 0).sum())}
        )
    out.append(table(pd.DataFrame(repairs)))
    out.append(
        "\nThe row counts are dominated by two feeds and neither lost any service. "
        "Bogor writes all 144 daily passes of each trip into `stop_times.txt` under one `trip_id`, "
        "while `frequencies.txt` already states the 60-second headway; the repair keeps the template pass "
        "and the service level comes from the headway, which is what GTFS specifies "
        "(its computed waiting time is 0.5 min, exactly half the headway). "
        "Moscow's rows are the 7 416 trips its own `trips.txt` never declares.\n"
    )
    if "zero_time_share" in gtfs:
        broken = gtfs.loc[gtfs["zero_time_share"].fillna(0) >= 1.0, "city_key"].tolist()
        out.append(f"\nCities whose schedule carries no run time at all: {', '.join(broken) or 'none'}.\n")

    # --- coverage ---------------------------------------------------------
    coverage = load("indicators_coverage.csv", ["city_key", "mode"])
    per_mode = coverage.loc[
        ~coverage["mode"].eq("*")
        & coverage["status"].eq("ok")
        & coverage["fetchable_from_osm"].astype(str).str.lower().eq("true")
    ]
    out.append(section("Coverage: does the other source know this stop?"))
    # Both shares are reported over the cities where both sources run the mode.
    # Taking each direction over its own population mixed two questions: the
    # reverse share for the subway came out 0.000 because OSM has a subway in 28
    # cities and only 9 of their feeds mention one, so the median fell on a city
    # whose feed has no subway to match. Which modes each source has at all is a
    # separate finding, reported in the next table.
    rows = []
    for mode in MODE_ORDER:
        both = per_mode.loc[per_mode["mode"].eq(mode) & per_mode["n_feed_stops"].gt(0) & per_mode["n_osm_stops"].gt(0)]
        if len(both) < 2:
            continue
        rows.append(
            {
                "mode": mode,
                "cities with both": len(both),
                "feed→OSM 50 m": round(both["feed_to_osm_50"].median(), 3),
                "feed→OSM 100 m": round(both["feed_to_osm_100"].median(), 3),
                "feed→OSM 150 m": round(both["feed_to_osm_150"].median(), 3),
                "IQR at 100 m": f"{both['feed_to_osm_100'].quantile(0.25):.2f}–{both['feed_to_osm_100'].quantile(0.75):.2f}",
                "OSM→feed 100 m": round(both["osm_to_feed_100"].median(), 3),
            }
        )
    out.append(table(pd.DataFrame(rows)))

    out.append("\nWhich source runs the mode at all:\n\n")
    rows = []
    for mode in MODE_ORDER:
        in_feed = per_mode.loc[per_mode["mode"].eq(mode) & per_mode["n_feed_stops"].gt(0)]
        in_osm = per_mode.loc[per_mode["mode"].eq(mode) & per_mode["n_osm_stops"].gt(0)]
        if len(in_feed) < 2 and len(in_osm) < 2:
            continue
        only_osm = per_mode.loc[
            per_mode["mode"].eq(mode) & per_mode["n_osm_stops"].gt(0) & per_mode["n_feed_stops"].eq(0)
        ]
        only_feed = per_mode.loc[
            per_mode["mode"].eq(mode) & per_mode["n_feed_stops"].gt(0) & per_mode["n_osm_stops"].eq(0)
        ]
        rows.append(
            {
                "mode": mode,
                "in the feed": len(in_feed),
                "in OSM": len(in_osm),
                "in both": len(in_feed) - len(only_feed),
                "OSM only": len(only_osm),
                "feed only": len(only_feed),
            }
        )
    out.append(table(pd.DataFrame(rows)))

    bus = classify_bus(per_mode)
    cases = (
        bus.groupby("case")
        .agg(
            cities=("city_key", "size"),
            median_coverage=("feed_to_osm_100", "median"),
            median_distance_m=("nearest_median_m", "median"),
        )
        .round(3)
        .reset_index()
        .sort_values("cities", ascending=False)
    )
    out.append("\nLow coverage is not one phenomenon:\n\n")
    out.append(table(cases))

    # --- what OSM maps against what it routes -------------------------------
    census = load("route_stops.csv", ["city_key"])
    if census is not None and "stop_nodes_in_boundary" in census:
        out.append(section("Stops OSM holds against stops a route reaches"))
        merged = classify_bus(per_mode).merge(
            census[["city_key", "stop_nodes_in_boundary", "n_relations"]], on="city_key", how="left"
        )
        rows = []
        for case in CASE_ORDER:
            group = merged.loc[merged["case"].eq(case)]
            if group.empty:
                continue
            rows.append(
                {
                    "case": case,
                    "cities": len(group),
                    "stops mapped in OSM": int(group["stop_nodes_in_boundary"].median()),
                    "stops on a route": int(group["n_osm_stops"].median()),
                    "route relations": int(group["n_relations"].median()),
                    "stops in the feed": int(group["n_feed_stops"].median()),
                }
            )
        out.append(table(pd.DataFrame(rows)))

        no_network = merged.loc[merged["case"].eq(NO_NETWORK)]
        with_stops = no_network.loc[no_network["stop_nodes_in_boundary"].fillna(0) >= 20]
        out.append(
            chr(10) + f"Of the {len(no_network)} cities whose bus network OSM does not route, "
            f"{len(with_stops)} have 20 or more bus stops mapped inside the boundary all the same"
            + (
                ": "
                + ", ".join(
                    f"{row.city_key} {int(row.stop_nodes_in_boundary)}"
                    for row in with_stops.nlargest(6, "stop_nodes_in_boundary").itertuples()
                )
                if not with_stops.empty
                else ""
            )
            + ". A stop belonging to no route relation cannot be routed through, so it never "
            "enters the graph and never enters the coverage figures." + chr(10)
        )

    # --- waiting ----------------------------------------------------------
    waits = load("indicators_waits.csv", ["city_key", "mode"])
    waits = waits.loc[waits["status"].eq("ok") & waits["wait_harmonic_min"].notna()]
    out.append(section("Waiting time, harmonic within a city and median across cities"))
    rows = []
    for mode in WAIT_MODE_ORDER:
        values = waits.loc[waits["mode"].eq(mode), "wait_harmonic_min"]
        if len(values) < 2:
            continue
        rows.append(
            {
                "mode": mode,
                "cities": len(values),
                "median, min": round(values.median(), 2),
                "IQR": f"{values.quantile(0.25):.1f}–{values.quantile(0.75):.1f}",
            }
        )
    out.append(table(pd.DataFrame(rows)))

    # --- kinematics -------------------------------------------------------
    speed = load("speed_by_length.csv")
    out.append(section("Observed speed against segment length"))
    pivot = speed.pivot(index="length_class", columns="mode", values="median")
    pivot.index = pivot.index.astype(str)
    order = sorted(pivot.index, key=lambda label: float(label.split(",")[0].strip("(")))
    pivot = pivot.reindex(order).reset_index().rename(columns={"length_class": "length, m"})
    out.append(table(pivot.round(1)))

    fit = load("kinematics_fit.csv")
    out.append(section("Kinematic calibration, and what generalises"))
    columns = [
        "mode",
        "scope",
        "cities",
        "pairs",
        "current_error",
        "fitted_error",
        "loco_error",
        "fitted_dwell_min",
        "fitted_base_speed_kmh",
    ]
    shown = fit[[c for c in columns if c in fit]].copy()
    shown["adopted"] = np.where(shown["loco_error"] < shown["current_error"], "yes", "no")
    out.append(table(shown.round(4)))
    pairs = load("matched_segments_summary.csv", ["city_key"])
    out.append(
        f"\nMatched segments: {int(pairs['n_matched'].fillna(0).sum()):,} pairs over "
        f"{int((pairs['n_matched'].fillna(0) > 0).sum())} cities.\n"
    )

    # --- provenance -------------------------------------------------------
    provenance = load("feed_provenance.csv", ["city_key"])
    measurable = provenance.loc[provenance["status"].eq("ok")]
    derived = measurable.loc[measurable["coincident_share"] >= 0.30].sort_values("coincident_share", ascending=False)
    out.append(section("Feed provenance: geometry copied from OSM"))
    out.append(
        f"{len(derived)} of {len(measurable)} measurable feeds were generated from OSM "
        f"(threshold 0.30); {int((measurable['coincident_share'] < 0.05).sum())} are clearly surveyed (< 0.05).\n\n"
    )
    out.append(table(derived[["city_key", "coincident_share", "median_distance_m"]].round(3).head(20)))

    # --- accessibility ----------------------------------------------------
    city_level = coverage.loc[coverage["mode"].eq("*") & coverage["status"].eq("ok")]
    table_access = access.loc[access["status"].eq("ok")].merge(
        city_level[["city_key", "feed_to_osm_100", "osm_to_feed_100"]], on="city_key", how="inner"
    )
    table_access["relative_completeness"] = table_access["feed_to_osm_100"] - table_access["osm_to_feed_100"]
    out.append(section("Accessibility: OSM estimate against the schedule reference"))
    rows = []
    for threshold in (15, 30, 45):
        values = table_access[f"ratio_{threshold}"].dropna()
        rows.append(
            {
                "threshold": f"{threshold} min",
                "cities": len(values),
                "median": round(values.median(), 3),
                "p10": round(values.quantile(0.10), 3),
                "p90": round(values.quantile(0.90), 3),
                "min": round(values.min(), 3),
                "max": round(values.max(), 3),
            }
        )
    out.append(table(pd.DataFrame(rows)))

    out.append("\nWhat predicts the error (Spearman against the signed ratio):\n\n")
    rows = []
    for threshold in (15, 30, 45):
        for label, column in (
            ("relative completeness", "relative_completeness"),
            ("OSM completeness alone", "feed_to_osm_100"),
            ("feed completeness alone", "osm_to_feed_100"),
        ):
            subset = table_access[[f"ratio_{threshold}", column]].dropna()
            rho, p = spearmanr(subset[column], subset[f"ratio_{threshold}"])
            rows.append(
                {
                    "threshold": f"{threshold} min",
                    "predictor": label,
                    "n": len(subset),
                    "rho": round(rho, 3),
                    "p": f"{p:.2e}" if p < 0.001 else round(p, 4),
                }
            )
    out.append(table(pd.DataFrame(rows)))

    out.append("\nMost underestimated and most overestimated at 30 minutes:\n\n")
    extremes = pd.concat([table_access.nsmallest(6, "ratio_30"), table_access.nlargest(6, "ratio_30")])
    out.append(table(extremes[["city_key", "feed_to_osm_100", "osm_to_feed_100", "ratio_30"]].round(3)))

    out.append(_robustness())
    return "".join(out)


def _robustness() -> str:
    """The predictor recomputed under other defensible constants, if those ran.

    The fit is flat, so a reviewer is owed an answer to "does this depend on which
    point of the valley you took". The answer is produced by
    ``benchmarks/wide_robustness.py``; this only reports it, and says nothing at
    all when the variants have not been run.
    """
    sys.path.insert(0, str(RESULTS.parents[1] / "benchmarks"))
    try:
        from wide_robustness import VARIANTS, correlations, variant_csv
    except ImportError:
        return ""

    frames = {"41.0 / 0.475 (standing)": load("accessibility.csv", ["city_key"])}
    for variant, fields in VARIANTS.items():
        path = variant_csv(variant)
        if path.exists():
            bus = fields["bus"]
            frames[f"{bus['base_speed_kmh']} / {bus['dwell_min']}"] = pd.read_csv(path)
    if len(frames) == 1:
        return ""

    rows = []
    for label, frame in frames.items():
        for _, row in correlations(frame).iterrows():
            rows.append({"bus speed / dwell": label, **row.to_dict()})
    out = [section("Does the conclusion depend on which constants were chosen?")]
    out.append(
        "Three settings within two per cent of each other on the same matched segments, "
        "each with its own transit graphs and its own accessibility sweep.\n\n"
    )
    out.append(table(pd.DataFrame(rows)))
    return "".join(out)


if __name__ == "__main__":
    OUTPUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"written {OUTPUT}")
